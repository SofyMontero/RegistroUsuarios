    public void start() {
        Notifiacion.setText("");
        lector.startCapture();
        setTexto("Utilizando el lector de huella dactilar");
        if (!vigilanteActivo) {
            vigilante.iniciar();
            vigilanteActivo = true;
            boolean modoUno = documentoObjetivo != null && !documentoObjetivo.isEmpty();
            emitirEvento("lectura_iniciada", modoUno ? "1:1" : "1:N");
        }
    }

