    public void Iniciar() {

        if (listenersAdd == false) {
            lector.addDataListener(new DPFPDataAdapter() {
                @Override
                public void dataAcquired(final DPFPDataEvent e) {
                    SwingUtilities.invokeLater(() -> {
                        try {
                            vigilante.marcarActividad();
                            setTexto("Huella dactilar capturada.!");
                            ProcesarCaptura(e.getSample());
                            identificarHuella();
                            reclutador.clear();
                        } catch (IOException ex) {
                            RegistroArchivo.error("Error de E/S procesando muestra de verificación", ex);
                        } catch (Exception ex) {
                            RegistroArchivo.error("Error inesperado procesando muestra de verificación", ex);
                        }
                    });
                }
            });

            lector.addReaderStatusListener(new DPFPReaderStatusAdapter() {
                @Override
                public void readerConnected(final DPFPReaderStatusEvent e) {
                    SwingUtilities.invokeLater(new Runnable() {
                        @Override
                        public void run() {
                            setTexto("Sensor activado o conectado.!");
                        }
                    });
                }

                @Override
                public void readerDisconnected(final DPFPReaderStatusEvent e) {
                    SwingUtilities.invokeLater(new Runnable() {
                        @Override
                        public void run() {
                            setTexto("Sensor desactivado o no conectado.!");
                        }
                    });
                }
            });

            lector.addSensorListener(new DPFPSensorAdapter() {

                @Override
                public void fingerTouched(final DPFPSensorEvent e) {
                    SwingUtilities.invokeLater(new Runnable() {
                        @Override
                        public void run() {
                            setTexto("Dedo colocado sobre el lector.!");
                        }
                    });
                }

                @Override
                public void fingerGone(final DPFPSensorEvent e) {
                    SwingUtilities.invokeLater(new Runnable() {
                        @Override
                        public void run() {
                            setTexto("Dedo retirado del lector.!");
                        }
                    });
                }

            });

            lector.addErrorListener(new DPFPErrorAdapter() {

                public void errorReader(final DPFPErrorEvent e) {
                    SwingUtilities.invokeLater(new Runnable() {
                        @Override
                        public void run() {
                            setTexto("Ocurrio un error con el lector.!");
                        }
                    });
                }
            });
        }

        listenersAdd = true;
    }

